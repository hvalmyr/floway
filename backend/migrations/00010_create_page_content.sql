-- +goose Up
-- Generic key/value store for freeform site copy (Hero-тексты, блоки
-- пояснений, юридические страницы и т.п.) — то, что не имеет собственной
-- структуры/списка и потому не заслуживает отдельной таблицы, но должно
-- редактироваться из админки без деплоя. `key` — стабильный идентификатор,
-- на который ссылается фронтенд (см. usePageContent()); `label` — понятное
-- админу описание поля.
CREATE TABLE page_content (
    key        TEXT PRIMARY KEY,
    label      TEXT NOT NULL,
    value      TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

